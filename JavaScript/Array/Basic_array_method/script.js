let movies = [1,"Chavva",2,"Pawankhind",3,"Thumbad",4,"Hridiyam",5,"Laila Majnu"]

// Push() - It is Array Method which is used to add element at the last index
movies.push("Premalu")
movies.push("Pushpa")
console.log(movies);

// Pop() - It is Array Method which is used to remove array element from the last index
movies.pop()
console.log(movies);

// Unshift() - It is an Array Method which is used to add array element at the zeroth index
movies.unshift(11)
console.log(movies);

// Shift() - It is an Array Method which is used to Remove array element at the zeroth index
movies.shift()  
console.log(movies);
